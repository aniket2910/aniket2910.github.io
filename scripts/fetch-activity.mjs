// Pulls the last year of GitHub contributions + LeetCode submissions, merged
// per day, plus LeetCode solved counts, and writes them to
// packages/content/src/data/activity.ts.
// Runs in CI before every build (and nightly via the deploy workflow's cron).
// If either source fails, the committed snapshot is left untouched so the
// build never breaks on a flaky upstream.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const GITHUB_USER = "aniket2910";
const LEETCODE_USER = "solankianiket0411";
const OUT = new URL("../packages/content/src/data/activity.ts", import.meta.url);

function githubToken() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  try {
    return execSync("gh auth token", { encoding: "utf8" }).trim();
  } catch {
    throw new Error("no GITHUB_TOKEN and `gh auth token` unavailable");
  }
}

async function fetchGithub() {
  const query = `query($u:String!){user(login:$u){contributionsCollection{contributionCalendar{weeks{contributionDays{date contributionCount}}}}}}`;
  const res = await fetch("https://api.github.com/graphql", {
    method: "POST",
    headers: { Authorization: `bearer ${githubToken()}`, "Content-Type": "application/json" },
    body: JSON.stringify({ query, variables: { u: GITHUB_USER } }),
  });
  const json = await res.json();
  const weeks = json.data?.user?.contributionsCollection?.contributionCalendar?.weeks;
  if (!weeks) throw new Error(`GitHub: ${JSON.stringify(json.errors ?? json)}`);
  return new Map(weeks.flatMap((w) => w.contributionDays.map((d) => [d.date, d.contributionCount])));
}

async function fetchLeetcode() {
  const query = `query($u:String!){matchedUser(username:$u){userCalendar{submissionCalendar} submitStatsGlobal{acSubmissionNum{difficulty count}}}}`;
  const res = await fetch("https://leetcode.com/graphql", {
    method: "POST",
    headers: { "Content-Type": "application/json", Referer: "https://leetcode.com" },
    body: JSON.stringify({ query, variables: { u: LEETCODE_USER } }),
  });
  const json = await res.json();
  const user = json.data?.matchedUser;
  const raw = user?.userCalendar?.submissionCalendar;
  const ac = user?.submitStatsGlobal?.acSubmissionNum;
  if (!raw || !ac) throw new Error(`LeetCode: ${JSON.stringify(json.errors ?? json)}`);
  const count = (level) => ac.find((a) => a.difficulty === level)?.count ?? 0;
  const solved = { total: count("All"), easy: count("Easy"), medium: count("Medium"), hard: count("Hard") };
  // Calendar keys are unix seconds at UTC midnight.
  const calendar = new Map(
    Object.entries(JSON.parse(raw)).map(([ts, n]) => [
      new Date(Number(ts) * 1000).toISOString().slice(0, 10),
      n,
    ]),
  );
  return { calendar, solved };
}

// 53 week-columns ending today, starting on a Sunday (same grid as GitHub).
function dateRange() {
  const today = new Date();
  today.setUTCHours(0, 0, 0, 0);
  const start = new Date(today);
  start.setUTCDate(today.getUTCDate() - 52 * 7 - today.getUTCDay());
  const dates = [];
  for (let d = start; d <= today; d.setUTCDate(d.getUTCDate() + 1)) {
    dates.push(d.toISOString().slice(0, 10));
  }
  return dates;
}

try {
  const [gh, { calendar: lc, solved }] = await Promise.all([fetchGithub(), fetchLeetcode()]);
  const days = dateRange().map((date) => ({ date, gh: gh.get(date) ?? 0, lc: lc.get(date) ?? 0 }));
  const body =
    `// GENERATED by scripts/fetch-activity.mjs — do not edit by hand.\n` +
    `import type { Activity } from "../types";\n\n` +
    `export const activity: Activity = ${JSON.stringify({ generatedAt: new Date().toISOString(), solved, days })};\n`;
  writeFileSync(OUT, body);
  const sum = (k) => days.reduce((n, d) => n + d[k], 0);
  console.log(`activity: ${days.length} days, ${sum("gh")} contributions, ${sum("lc")} submissions, ${solved.total} solved`);
} catch (err) {
  console.warn(`activity: fetch failed, keeping existing snapshot (${err.message})`);
}
